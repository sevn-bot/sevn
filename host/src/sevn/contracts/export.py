"""Deterministic JSON Schema for frames, methods, and events (D18)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import cast

from pydantic import BaseModel

from sevn.contracts.errors import ErrorBody
from sevn.contracts.events import EVENTS, EventSpec
from sevn.contracts.frames import FRAME_MODELS
from sevn.contracts.methods import METHODS, MethodSpec


def build_schema() -> dict[str, object]:
    document: dict[str, object] = {
        "$defs": _definitions(),
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "events": {
            spec.name: {"durable": spec.durable}
            for spec in sorted(EVENTS.values(), key=_event_name)
        },
        "methods": {
            spec.name: {
                "mutating": spec.mutating,
                "params": spec.params.__name__,
                "result": spec.result.__name__,
            }
            for spec in sorted(METHODS.values(), key=_method_name)
        },
        "oneOf": [{"$ref": f"#/$defs/{model.__name__}"} for model in FRAME_MODELS],
        "title": "Frame",
    }
    return _stable(document)


def _definitions() -> dict[str, object]:
    defs: dict[str, object] = {}
    for model in (*FRAME_MODELS, ErrorBody, *_method_models()):
        schema = cast("dict[str, object]", model.model_json_schema())
        nested = schema.pop("$defs", None)
        if isinstance(nested, dict):
            extra = cast("dict[str, object]", nested)
            for key, value in extra.items():
                defs.setdefault(key, value)
        defs[model.__name__] = schema
    return defs


def _method_models() -> list[type[BaseModel]]:
    models: list[type[BaseModel]] = []
    for spec in METHODS.values():
        models.append(spec.params)
        models.append(spec.result)
    return models


def _method_name(spec: MethodSpec) -> str:
    return spec.name


def _event_name(spec: EventSpec) -> str:
    return spec.name


def _stable(document: dict[str, object]) -> dict[str, object]:
    encoded = json.dumps(document, sort_keys=True, separators=(",", ":"))
    loaded = json.loads(encoded)
    if not isinstance(loaded, dict):
        raise RuntimeError("schema root must be an object")
    return cast("dict[str, object]", loaded)


def schema_text() -> str:
    """Canonical ``protocol.schema.json`` body (sorted keys, trailing newline)."""
    return json.dumps(build_schema(), indent=2, sort_keys=True) + "\n"


def methods_module() -> str:
    """TypeScript method table: name, params type, result type, mutating flag."""
    raw = build_schema()["methods"]
    if not isinstance(raw, dict):
        raise RuntimeError("schema methods must be an object")
    methods = cast("dict[str, object]", raw)
    lines = [
        "// Generated by `sevn contracts export`. Do not edit.",
        "",
        "export const methods = {",
    ]
    for name in sorted(methods):
        spec = methods[name]
        if not isinstance(spec, dict):
            raise RuntimeError(f"method {name} must be an object")
        body = cast("dict[str, object]", spec)
        mutating = body.get("mutating")
        params = body.get("params")
        result = body.get("result")
        row_ok = isinstance(mutating, bool) and isinstance(params, str) and isinstance(result, str)
        if not row_ok:
            raise RuntimeError(f"method {name} has an invalid table row")
        flag = "true" if mutating else "false"
        lines.append(f"  {json.dumps(name)}: {{")
        lines.append(f"    mutating: {flag},")
        lines.append(f"    params: {json.dumps(params)},")
        lines.append(f"    result: {json.dumps(result)},")
        lines.append("  },")
    lines.append("} as const;")
    lines.append("")
    return "\n".join(lines)


def export_contracts(root: Path) -> None:
    """Write the schema and ``methods.ts`` under ``root``."""
    schema_path = root / "contracts" / "protocol.schema.json"
    methods_path = root / "web" / "src" / "contracts" / "methods.ts"
    schema_path.parent.mkdir(parents=True, exist_ok=True)
    methods_path.parent.mkdir(parents=True, exist_ok=True)
    schema_path.write_text(schema_text(), encoding="utf-8")
    methods_path.write_text(methods_module(), encoding="utf-8")
